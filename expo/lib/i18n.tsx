export const dicts: Record<string, Dict> = { en, fr, pt, sw, ar };

export type T = (key: string) => string;

/** Translation hook driven by the stored language preference. */
export function useI18n(): { t: T; isRTL: boolean; lang: string } {
  const { settings } = useStore();
  const lang = dicts[settings.language] ? settings.language : "en";
  const d = dicts[lang];
  const t: T = (key) => d[key] ?? en[key] ?? key;
  return { t, isRTL: lang === "ar", lang };
}

/** Applies RTL layout for Arabic (takes effect after an app restart). */
export function applyDirection(lang: string): boolean {
  const rtl = lang === "ar";
  I18nManager.allowRTL(rtl);
  I18nManager.forceRTL(rtl);
  return rtl;
}
